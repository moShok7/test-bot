<?php

namespace App\Services\Bot;

use App\Models\ChatMessage;
use App\Models\TelegramUser;
use Telegram\Bot\Api;

class GlobalChatHandler
{
    public function handle($message, Api $telegram): bool
    {
        /*
        |--------------------------------------------------------------------------
        | Текст сообщения
        |--------------------------------------------------------------------------
        */

        $text = trim($message->text ?? '');

        if ($text === '') {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Telegram ID пользователя
        |--------------------------------------------------------------------------
        */

        $telegramUserId = $message->from->id ?? null;

        if (!$telegramUserId) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Актуальные данные пользователя из Telegram
        |--------------------------------------------------------------------------
        */

        $username = $message->from->username ?? null;

        $firstName = $message->from->first_name
            ?? 'Пользователь';

        /*
        |--------------------------------------------------------------------------
        | Создаём или обновляем пользователя
        |--------------------------------------------------------------------------
        |
        | Telegram ID постоянный.
        | Username может измениться.
        |
        */

        $user = TelegramUser::updateOrCreate(
            [
                'telegram_id' => $telegramUserId,
            ],
            [
                'username' => $username,
                'first_name' => $firstName,
            ]
        );

        /*
        |--------------------------------------------------------------------------
        | Сохраняем сообщение
        |--------------------------------------------------------------------------
        */

        ChatMessage::create([
            'telegram_user_id' => $user->id,
            'message' => $text,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Имя автора
        |--------------------------------------------------------------------------
        */

        $authorName = $username
            ? '@' . $username
            : $firstName;

        /*
        |--------------------------------------------------------------------------
        | Делаем имя кликабельным
        |--------------------------------------------------------------------------
        */

        $authorLink = '<a href="tg://user?id='
            . $telegramUserId
            . '">'
            . htmlspecialchars(
                $authorName,
                ENT_QUOTES,
                'UTF-8'
            )
            . '</a>';

        /*
        |--------------------------------------------------------------------------
        | Формируем сообщение
        |--------------------------------------------------------------------------
        |
        | Вид:
        |
        | @moShok7
        | 👤 Привет всем
        |
        */

        $chatText =
            $authorLink
            . "\n"
            . "👤 "
            . htmlspecialchars(
                $text,
                ENT_QUOTES,
                'UTF-8'
            );

       /*
|--------------------------------------------------------------------------
| Получаем пользователей, у которых включены уведомления
|--------------------------------------------------------------------------
*/

$users = TelegramUser::where(
    'telegram_id',
    '!=',
    $telegramUserId
)
->where('chat_notifications', true)
->get();

/*
|--------------------------------------------------------------------------
| Рассылаем сообщение
|--------------------------------------------------------------------------
*/

foreach ($users as $recipient) {
    try {
        $telegram->sendMessage([
            'chat_id' => $recipient->telegram_id,
            'text' => $chatText,
            'parse_mode' => 'HTML',
        ]);
    } catch (\Throwable $e) {
        \Log::warning(
            'Global chat send error',
            [
                'telegram_user_id' => $recipient->id,
                'message' => $e->getMessage(),
            ]
        );
    }
}