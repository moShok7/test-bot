<?php

namespace App\Services\Bot\Lobby;

use App\Models\BotSession;
use App\Models\TelegramUser;
use App\Models\Lobby;

class SearchLobbyHandler
{
    public function handle($message, $telegram): bool
    {
        $text = trim($message->text ?? '');

        /*
        |--------------------------------------------------------------------------
        | Обрабатываем только кнопки поиска
        |--------------------------------------------------------------------------
        */

        if (
            $text !== '🔍 Найти лобби' &&
            $text !== '🔄 Обновить поиск'
        ) {
            return false;
        }

        $chatId = $message->chat->id ?? null;
        $telegramId = $message->from->id ?? null;

        if (!$telegramId || !$chatId) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Получаем TelegramUser
        |--------------------------------------------------------------------------
        */

        $telegramUser = TelegramUser::where(
            'telegram_id',
            $telegramId
        )->first();

        if (!$telegramUser) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Удаляем сессию создания лобби
        |--------------------------------------------------------------------------
        */

        BotSession::where(
            'telegram_user_id',
            $telegramUser->id
        )->delete();

        /*
        |--------------------------------------------------------------------------
        | Ищем доступные лобби
        |--------------------------------------------------------------------------
        */

        $lobbies = Lobby::where(
            'status',
            'waiting'
        )
        ->where(
            'creator_id',
            '!=',
            $telegramUser->id
        )
        ->with('creator')
        ->withCount('players')
        ->latest()
        ->limit(10)
        ->get();

        $found = false;

        /*
        |--------------------------------------------------------------------------
        | Показываем лобби
        |--------------------------------------------------------------------------
        */

        foreach ($lobbies as $lobby) {

            /*
            |--------------------------------------------------------------------------
            | Пропускаем заполненные лобби
            |--------------------------------------------------------------------------
            */

            if (
                $lobby->players_count >=
                $lobby->max_players
            ) {
                continue;
            }

            /*
            |--------------------------------------------------------------------------
            | Если у лобби ещё нет кода игры
            |--------------------------------------------------------------------------
            */

            if (empty($lobby->game_room_code)) {
                continue;
            }

            $found = true;

            /*
            |--------------------------------------------------------------------------
            | Имя хоста
            |--------------------------------------------------------------------------
            */

            $hostNickname = 'Игрок';

            if ($lobby->creator) {

                if (
                    !empty(
                        $lobby->creator->first_name
                    )
                ) {

                    $hostNickname =
                        $lobby->creator->first_name;

                } elseif (
                    !empty(
                        $lobby->creator->username
                    )
                ) {

                    $hostNickname =
                        '@' .
                        $lobby->creator->username;
                }
            }

            /*
            |--------------------------------------------------------------------------
            | Прямая ссылка в игру
            |--------------------------------------------------------------------------
            */

            $gameLink =
                "https://play.suspects.io/?code=" .
                $lobby->game_room_code;

            /*
            |--------------------------------------------------------------------------
            | Отправляем лобби
            |--------------------------------------------------------------------------
            */

            $telegram->sendMessage([
                'chat_id' =>
                    $chatId,

                'text' =>
                    "🎮 Лобби #{$lobby->id}\n" .
                    "👑 Хост: {$hostNickname}\n" .
                    "👥 Игроки: {$lobby->players_count}/{$lobby->max_players}\n" .
                    "🔑 Код: {$lobby->game_room_code}\n" .
                    "⏳ Ожидание игроков",

                'reply_markup' => json_encode([
                    'inline_keyboard' => [
                        [
                            [
                                'text' =>
                                    '🎮 Войти в игру',

                                'url' =>
                                    $gameLink,
                            ],
                        ],
                        [
                            [
                                'text' =>
                                    '📋 Скопировать код',

                                'copy_text' => [
                                    'text' =>
                                        $lobby->game_room_code,
                                ],
                            ],
                        ],
                    ],
                ]),
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | Если лобби не найдены
        |--------------------------------------------------------------------------
        */

        if (!$found) {

            $telegram->sendMessage([
                'chat_id' =>
                    $chatId,

                'text' =>
                    "😔 Сейчас нет доступных лобби.",
            ]);
        }

        /*
        |--------------------------------------------------------------------------
        | Меню после поиска
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' =>
                $chatId,

            'text' =>
                "🔍 Поиск завершён.\n\n" .

                (
                    $found
                        ? "Выберите подходящее лобби выше."
                        : "😔 Активных лобби пока нет.\n\n" .
                          "Вы можете создать своё лобби и ждать игроков."
                ),

            'reply_markup' => json_encode([
                'keyboard' => [

                    [
                        [
                            'text' =>
                                '🔄 Обновить поиск',
                        ],
                    ],

                    [
                        [
                            'text' =>
                                '➕ Создать лобби',
                        ],
                    ],

                    [
                        [
                            'text' =>
                                '🎮 Моё лобби',
                        ],
                    ],

                    [
                        [
                            'text' =>
                                '⬅️ Главное меню',
                        ],
                    ],
                ],

                'resize_keyboard' => true,
            ]),
        ]);

        return true;
    }
}