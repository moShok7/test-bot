<?php

namespace App\Services\Bot\Lobby;

use App\Models\TelegramUser;
use App\Models\Lobby;

class HostLobbyHandler
{
    public function handle($message, $telegram): bool
    {
        $text = trim($message->text ?? '');

        $telegramId = $message->from->id ?? null;

        if (!$telegramId) {
            return false;
        }

        if ($text !== '🎮 Моё лобби') {
            return false;
        }

        $chatId = $message->chat->id;

        /*
        |--------------------------------------------------------------------------
        | Получаем TelegramUser
        |--------------------------------------------------------------------------
        */

        $user = TelegramUser::where(
            'telegram_id',
            $telegramId
        )->first();

        /*
        |--------------------------------------------------------------------------
        | Если пользователь ещё не зарегистрирован
        |--------------------------------------------------------------------------
        */

        if (!$user) {

            $telegram->sendMessage([
                'chat_id' => $chatId,
                'text' =>
                    "❌ Пользователь не найден.\n\n" .
                    "Нажмите /start, чтобы зарегистрироваться."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Ищем активное лобби пользователя
        |--------------------------------------------------------------------------
        */

        $lobby = Lobby::whereIn(
            'status',
            [
                'waiting',
                'playing'
            ]
        )
        ->where(function ($query) use ($user) {

            $query
                ->where(
                    'creator_id',
                    $user->id
                )
                ->orWhereHas(
                    'players',
                    function ($q) use ($user) {

                        $q->where(
                            'telegram_user_id',
                            $user->id
                        );

                    }
                );

        })
        ->withCount('players')
        ->with([
            'players.telegramUser.gameProfile'
        ])
        ->first();

        /*
        |--------------------------------------------------------------------------
        | Лобби не найдено
        |--------------------------------------------------------------------------
        */

        if (!$lobby) {

            $telegram->sendMessage([
                'chat_id' => $chatId,
                'text' =>
                    "❌ У вас нет активного лобби."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Статус
        |--------------------------------------------------------------------------
        */

        $status = $lobby->status === 'waiting'
            ? '⏳ Ожидание игроков'
            : '🎮 Игра идёт';

        /*
        |--------------------------------------------------------------------------
        | Проверяем, является ли пользователь хостом
        |--------------------------------------------------------------------------
        */

        $isHost = $lobby->creator_id == $user->id;

        /*
        |--------------------------------------------------------------------------
        | Кнопки
        |--------------------------------------------------------------------------
        */

        if ($isHost) {

            if ($lobby->status === 'playing') {

                $keyboard = [
                    [
                        ['text' => '👥 Игроки']
                    ],
                    [
                        ['text' => '🏁 Завершить игру']
                    ],
                    [
                        ['text' => '⬅️ Главное меню']
                    ],
                ];

            } else {

                $keyboard = [
                    [
                        ['text' => '👥 Игроки']
                    ],
                    [
                        ['text' => '❌ Кикнуть игрока']
                    ],
                    [
                        [
                            'text' =>
                                '📤 Приглашение'
                        ]
                    ],
                    [
                        ['text' => '▶️ Начать игру']
                    ],
                    [
                        ['text' => '✏️ Изменить код']
                    ],
                    [
                        ['text' => '🚪 Выйти из лобби']
                    ],
                    [
                        ['text' => '⬅️ Главное меню']
                    ],
                ];
            }

            $title = "👑 Панель хоста";

        } else {

            $keyboard = [
                [
                    ['text' => '👥 Игроки']
                ],
                 [
                            [
                                'text' => '📤 Приглашение'
                            ]
                        ],
                [
                    ['text' => '🚪 Выйти из лобби']
                ],
                [
                    ['text' => '⬅️ Главное меню']
                ],
            ];

            $title = "🎮 Моё лобби";
        }

        /*
        |--------------------------------------------------------------------------
        | Отправляем информацию о лобби
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([

            'chat_id' => $chatId,

            'text' =>
                "{$title}\n\n" .
                "🆔 Лобби #{$lobby->id}\n" .
                "🔑 Код комнаты: {$lobby->game_room_code}\n" .
                "👥 Игроки: {$lobby->players_count}/{$lobby->max_players}\n" .
                "📌 Статус: {$status}",

            'reply_markup' => json_encode([

                'keyboard' => $keyboard,

                'resize_keyboard' => true

            ])

        ]);

        return true;
    }
}