<?php

namespace App\Services\Bot\Lobby;

use App\Models\BotSession;
use App\Models\TelegramUser;
use App\Models\Lobby;
use App\Models\LobbyNotification;
use App\Models\LobbyPlayer;

class CreateLobbyHandler
{
    public function handle($message, $telegram): bool
    {
        $text = trim($message->text ?? '');

        $telegramId = $message->from->id ?? null;

        if (!$telegramId) {
            return false;
        }

        $chatId = $message->chat->id;

        /*
        |--------------------------------------------------------------------------
        | Главное меню
        |--------------------------------------------------------------------------
        */

        if ($text === '⬅️ Главное меню') {

            BotSession::where(
                'telegram_user_id',
                $telegramId
            )->delete();

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' => '🏠 Главное меню',

                'reply_markup' => json_encode([
                    'keyboard' => [
                        [
                            [
                                'text' => '➕ Создать лобби'
                            ],
                            [
                                'text' => '🔍 Найти лобби'
                            ]
                        ],
                        [
                            [
                                'text' => '🎮 Моё лобби'
                            ]
                        ],
                        [
    [
        'text' => '⚙️ Настройки'
    ]
]
                    ],

                    'resize_keyboard' => true
                ])
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Эти кнопки обрабатывает SearchLobbyHandler
        |--------------------------------------------------------------------------
        */

        if (
            $text === '🔍 Найти лобби' ||
            $text === '🔄 Обновить поиск'
        ) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Получаем TelegramUser
        |--------------------------------------------------------------------------
        */

        $user = TelegramUser::where(
            'telegram_id',
            $telegramId
        )->first();

        if (!$user) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Нажата кнопка "Создать лобби"
        |--------------------------------------------------------------------------
        */

        if ($text === '➕ Создать лобби') {

            /*
            |--------------------------------------------------------------------------
            | Проверяем активное лобби
            |--------------------------------------------------------------------------
            */

            $already = LobbyPlayer::where(
                'telegram_user_id',
                $user->id
            )
            ->whereHas(
                'lobby',
                function ($query) {
                    $query->whereIn(
                        'status',
                        [
                            'waiting',
                            'playing'
                        ]
                    );
                }
            )
            ->exists();

            /*
            |--------------------------------------------------------------------------
            | Если пользователь уже в лобби
            |--------------------------------------------------------------------------
            */

            if ($already) {

                $lobby = Lobby::whereIn(
                    'status',
                    [
                        'waiting',
                        'playing'
                    ]
                )
                ->whereHas(
                    'players',
                    function ($q) use ($user) {
                        $q->where(
                            'telegram_user_id',
                            $user->id
                        );
                    }
                )
                ->first();

                $isHost =
                    $lobby &&
                    $lobby->creator_id == $user->id;

                if ($isHost) {

                    $keyboard = [

                        [
                            [
                                'text' => '👥 Игроки'
                            ]
                        ],

                        [
                            [
                                'text' => '❌ Кикнуть игрока'
                            ]
                        ],

                        [
                            [
                                'text' => '📤 Приглашение'
                            ]
                        ],

                        [
                            [
                                'text' => '▶️ Начать игру'
                            ]
                        ],

                        [
                            [
                                'text' => '✏️ Изменить код'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];

                } else {

                    $keyboard = [

                        [
                            [
                                'text' => '🎮 Моё лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];
                }

                $telegram->sendMessage([
                    'chat_id' => $chatId,

                    'text' =>
                        "⚠️ Вы уже состоите в активном лобби.\n\n" .
                        "Откройте: 🎮 Моё лобби",

                    'reply_markup' => json_encode([
                        'keyboard' => $keyboard,
                        'resize_keyboard' => true
                    ])
                ]);

                return true;
            }

            /*
            |--------------------------------------------------------------------------
            | Создаём сессию ожидания кода
            |--------------------------------------------------------------------------
            */

            BotSession::updateOrCreate(
                [
                    'telegram_user_id' => $user->id
                ],
                [
                    'step' => 'lobby_code'
                ]
            );

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "🎮 Создайте комнату в игре.\n\n" .
                    "После этого отправьте код комнаты.\n\n" .
                    "Или нажмите кнопку ниже, чтобы вернуться.",

                'reply_markup' => json_encode([
                    'keyboard' => [
                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ],

                    'resize_keyboard' => true
                ])
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Получаем активную сессию
        |--------------------------------------------------------------------------
        */

        $session = BotSession::where(
            'telegram_user_id',
            $user->id
        )->first();

        /*
        |--------------------------------------------------------------------------
        | Обрабатываем код только при создании лобби
        |--------------------------------------------------------------------------
        */

        if (
            !$session ||
            $session->step !== 'lobby_code'
        ) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Проверяем код
        |--------------------------------------------------------------------------
        */

        if (!$text) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Отправьте код комнаты."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Максимальная длина
        |--------------------------------------------------------------------------
        */

        if (strlen($text) > 50) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Код комнаты слишком длинный.\n" .
                    "Отправьте только код из игры."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Разрешённые символы
        |--------------------------------------------------------------------------
        */

        if (!preg_match('/^[a-zA-Z0-9_-]+$/', $text)) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Неверный код комнаты.\n\n" .
                    "Используйте только буквы, цифры, _ и -."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Создаём лобби
        |--------------------------------------------------------------------------
        */

        $lobby = Lobby::create([
            'creator_id' =>
                $user->id,

            'game_room_code' =>
                $text,

            'status' =>
                'waiting',

            'min_players' =>
                4,

            'max_players' =>
                12,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Добавляем создателя в игроки
        |--------------------------------------------------------------------------
        */

        LobbyPlayer::create([
            'lobby_id' =>
                $lobby->id,

            'telegram_user_id' =>
                $user->id,

            'ready' =>
                false,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Удаляем сессию
        |--------------------------------------------------------------------------
        */

        $session->delete();

        /*
        |--------------------------------------------------------------------------
        | Количество игроков
        |--------------------------------------------------------------------------
        */

        $count = $lobby
            ->players()
            ->count();

        /*
        |--------------------------------------------------------------------------
        | Приглашение
        |--------------------------------------------------------------------------
        */

        $inviteLink =
            "https://t.me/YkSUS10_bot?start=lobby_{$lobby->id}";

        $creatorName = 'Игрок';
        if($user->username) {
            $creatorName = '@' . $user->username;
        } elseif ($user->first_name) {
            $creatorName = $user->first_name;
        }
        $inviteText =
            "🎮 Приглашение в лобби\n\n" .
            "👑 Создал: {$creatorName}\n" .
            "👥 Игроки: {$count}/{$lobby->max_players}\n" .
            "🔗 Войти в лобби:\n" .
            $inviteLink;

        /*
        |--------------------------------------------------------------------------
        | Получаем игроков, которые уже находятся
        | в активных лобби
        |--------------------------------------------------------------------------
        */

        $activePlayerIds = LobbyPlayer::whereHas(
            'lobby',
            function ($query) {
                $query->whereIn(
                    'status',
                    [
                        'waiting',
                        'playing'
                    ]
                );
            }
        )
        ->pluck('telegram_user_id')
        ->unique()
        ->toArray();

        /*
        |--------------------------------------------------------------------------
        | Выбираем пользователей для уведомления
        |--------------------------------------------------------------------------
        |
        | Создателю уведомление не отправляем.
        |
        */

        $notifyUsersQuery = TelegramUser::query()
            ->where(
                'telegram_id',
                '!=',
                $telegramId
            );

        /*
        |--------------------------------------------------------------------------
        | Исключаем игроков активных лобби
        |--------------------------------------------------------------------------
        */

        if (!empty($activePlayerIds)) {

            $notifyUsersQuery->whereNotIn(
                'id',
                $activePlayerIds
            );
        }

        $notifyUsers = $notifyUsersQuery->get();

        /*
        |--------------------------------------------------------------------------
        | Рассылаем уведомления
        |--------------------------------------------------------------------------
        */

        $creatorName = 'Игрок';

if ($user->username) {
    $creatorName = '@' . $user->username;
} elseif ($user->first_name) {
    $creatorName = $user->first_name;
}
/*
|--------------------------------------------------------------------------
| Рассылаем уведомления
|--------------------------------------------------------------------------
*/

foreach ($notifyUsers as $notifyUser) {

    try {

        $response = $telegram->sendMessage([
            'chat_id' =>
                $notifyUser->telegram_id,

            'text' =>
                "🔔 Новое лобби!\n\n" .
                "🎮 Лобби #{$lobby->id}\n" .
                "👑 Создал: {$creatorName}\n" .
                "👥 Игроков: {$count}/{$lobby->max_players}\n" .
                "⏳ Ожидание игроков\n\n" .
                "Хочешь присоединиться?",

            'reply_markup' => json_encode([
                'inline_keyboard' => [
                    [
                        [
                            'text' =>
                                '🚪 Войти в лобби',

                            'callback_data' =>
                                'join_lobby_' . $lobby->id
                        ]
                    ]
                ]
            ])
        ]);

        /*
        |--------------------------------------------------------------------------
        | Сохраняем сообщение, чтобы потом удалить
        |--------------------------------------------------------------------------
        */

        LobbyNotification::create([
            'lobby_id' =>
                $lobby->id,

            'telegram_user_id' =>
                $notifyUser->id,

            'telegram_message_id' =>
                $response->getMessageId(),
        ]);

    } catch (\Throwable $e) {

        \Log::warning(
            'Не удалось отправить уведомление о новом лобби',
            [
                'telegram_id' =>
                    $notifyUser->telegram_id,

                'lobby_id' =>
                    $lobby->id,

                'error' =>
                    $e->getMessage()
            ]
        );
    }
}

        /*
        |--------------------------------------------------------------------------
        | Сообщение создателю
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                "🎮 Лобби создано!\n\n" .
                "🆔 Лобби #{$lobby->id}\n" .
                "🔑 Код игры: {$lobby->game_room_code}\n\n" .
                "👥 Игроки: {$count}/{$lobby->max_players}\n\n" .
                "Ожидаем игроков.",

            'reply_markup' => json_encode([
                'inline_keyboard' => [
                    [
                        [
                            'text' =>
                                '📋 Скопировать приглашение',

                            'copy_text' => [
                                'text' =>
                                    $inviteText
                            ]
                        ]
                    ]
                ]
            ])
        ]);

        /*
        |--------------------------------------------------------------------------
        | Обычная клавиатура управления
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                '🎮 Управление лобби:',

            'reply_markup' => json_encode([
                'keyboard' => [
                    [
                        [
                            'text' =>
                                '🎮 Моё лобби'
                        ]
                    ],

                    [
                        [
                            'text' =>
                                '⬅️ Главное меню'
                        ]
                    ]
                ],

                'resize_keyboard' => true
            ])
        ]);

        return true;
    }
}