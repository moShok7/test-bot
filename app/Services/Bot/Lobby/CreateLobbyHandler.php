<?php

namespace App\Services\Bot\Lobby;

use App\Jobs\SendLobbyNotificationsJob;
use App\Models\BotSession;
use App\Models\TelegramUser;
use App\Models\Lobby;
use App\Models\LobbyPlayer;

class CreateLobbyHandler
{
    /*
    |--------------------------------------------------------------------------
    | Время жизни сессии создания лобби
    |--------------------------------------------------------------------------
    */

    private const SESSION_TIMEOUT_MINUTES = 5;


    public function handle($message, $telegram): bool
    {
        $text = trim($message->text ?? '');

        $telegramId = $message->from->id ?? null;

        if (!$telegramId) {
            return false;
        }

        $chatId = $message->chat->id ?? $telegramId;

        /*
        |--------------------------------------------------------------------------
        | Получаем TelegramUser
        |--------------------------------------------------------------------------
        */

        $user = TelegramUser::where(
            'telegram_id',
            $telegramId
        )->first();

        if (!$user) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Получаем текущую сессию
        |--------------------------------------------------------------------------
        */

        $session = BotSession::where(
            'telegram_user_id',
            $user->id
        )->first();

        /*
        |--------------------------------------------------------------------------
        | Удаляем просроченную сессию
        |--------------------------------------------------------------------------
        */

        if (
            $session &&
            $session->step === 'lobby_code' &&
            $session->updated_at &&
            $session->updated_at->lt(
                now()->subMinutes(
                    self::SESSION_TIMEOUT_MINUTES
                )
            )
        ) {
            $session->delete();

            $session = null;
        }

        /*
        |--------------------------------------------------------------------------
        | Главное меню
        |--------------------------------------------------------------------------
        */

        if ($text === '⬅️ Главное меню') {

            BotSession::where(
                'telegram_user_id',
                $user->id
            )->delete();

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' => '🏠 Главное меню',

                'reply_markup' => json_encode([
                    'keyboard' => [
                        [
                            [
                                'text' => '➕ Создать лобби'
                            ],
                            [
                                'text' => '🔍 Найти лобби'
                            ]
                        ],
                        [
                            [
                                'text' => '🎮 Моё лобби'
                            ]
                        ],
                        [
                            [
                                'text' => '⚙️ Настройки'
                            ]
                        ]
                    ],

                    'resize_keyboard' => true
                ])
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Поиск лобби
        |--------------------------------------------------------------------------
        |
        | Эти кнопки обрабатывает SearchLobbyHandler.
        |
        */

        if (
            $text === '🔍 Найти лобби' ||
            $text === '🔄 Обновить поиск'
        ) {

            BotSession::where(
                'telegram_user_id',
                $user->id
            )->delete();

            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Нажата кнопка "Создать лобби"
        |--------------------------------------------------------------------------
        */

        if ($text === '➕ Создать лобби') {

            /*
            |--------------------------------------------------------------------------
            | Проверяем активное лобби
            |--------------------------------------------------------------------------
            */

            $already = LobbyPlayer::where(
                'telegram_user_id',
                $user->id
            )
            ->whereHas(
                'lobby',
                function ($query) {
                    $query->whereIn(
                        'status',
                        [
                            'waiting',
                            'playing'
                        ]
                    );
                }
            )
            ->exists();

            /*
            |--------------------------------------------------------------------------
            | Если пользователь уже в лобби
            |--------------------------------------------------------------------------
            */

            if ($already) {

                $lobby = Lobby::whereIn(
                    'status',
                    [
                        'waiting',
                        'playing'
                    ]
                )
                ->whereHas(
                    'players',
                    function ($q) use ($user) {
                        $q->where(
                            'telegram_user_id',
                            $user->id
                        );
                    }
                )
                ->first();

                $isHost =
                    $lobby &&
                    $lobby->creator_id == $user->id;

                if ($isHost) {

                    $keyboard = [

                        [
                            [
                                'text' => '👥 Игроки'
                            ]
                        ],

                        [
                            [
                                'text' => '❌ Кикнуть игрока'
                            ]
                        ],

                        [
                            [
                                'text' => '📤 Приглашение'
                            ]
                        ],

                        [
                            [
                                'text' => '▶️ Начать игру'
                            ]
                        ],

                        [
                            [
                                'text' => '✏️ Изменить код'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];

                } else {

                    $keyboard = [

                        [
                            [
                                'text' => '🎮 Моё лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];
                }

                $telegram->sendMessage([
                    'chat_id' => $chatId,

                    'text' =>
                        "⚠️ Вы уже состоите в активном лобби.\n\n" .
                        "Откройте: 🎮 Моё лобби",

                    'reply_markup' => json_encode([
                        'keyboard' => $keyboard,
                        'resize_keyboard' => true
                    ])
                ]);

                return true;
            }

            /*
            |--------------------------------------------------------------------------
            | Создаём новую сессию
            |--------------------------------------------------------------------------
            */

            $session = BotSession::updateOrCreate(
                [
                    'telegram_user_id' => $user->id
                ],
                [
                    'step' => 'lobby_code'
                ]
            );

            /*
            |--------------------------------------------------------------------------
            | Просим код комнаты
            |--------------------------------------------------------------------------
            */

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "🎮 Создайте комнату в игре.\n\n" .
                    "После этого отправьте код комнаты.\n\n" .
                    "🔑 Код должен содержать ровно 6 символов.\n" .
                    "Разрешены только английские буквы и цифры.\n" .
                    "⏱ У вас есть 5 минут.\n\n" .
                    "Или нажмите кнопку ниже, чтобы вернуться.",

                'reply_markup' => json_encode([
                    'keyboard' => [
                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ],

                    'resize_keyboard' => true
                ])
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Если сессии нет
        |--------------------------------------------------------------------------
        */

        if (!$session) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Обрабатываем код только при создании лобби
        |--------------------------------------------------------------------------
        */

        if ($session->step !== 'lobby_code') {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Проверяем, что код не пустой
        |--------------------------------------------------------------------------
        */

        if (!$text) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Отправьте код комнаты.\n\n" .
                    "Пример: FJFAOO"
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Проверяем код комнаты
        |--------------------------------------------------------------------------
        |
        | Ровно 6 символов.
        | Только английские буквы A-Z / a-z и цифры 0-9.
        |
        */

        if (!preg_match('/^[A-Za-z0-9]{6}$/', $text)) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Неверный код комнаты.\n\n" .
                    "Код должен содержать ровно 6 символов.\n" .
                    "Используйте только английские буквы и цифры.\n\n"
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Создаём лобби
        |--------------------------------------------------------------------------
        */

        $lobby = Lobby::create([
            'creator_id' =>
                $user->id,

            'game_room_code' =>
                $text,

            'status' =>
                'waiting',

            'min_players' =>
                4,

            'max_players' =>
                12,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Добавляем создателя
        |--------------------------------------------------------------------------
        */

        LobbyPlayer::create([
            'lobby_id' =>
                $lobby->id,

            'telegram_user_id' =>
                $user->id,

            'ready' =>
                false,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Удаляем сессию
        |--------------------------------------------------------------------------
        */

        $session->delete();

        /*
        |--------------------------------------------------------------------------
        | Количество игроков
        |--------------------------------------------------------------------------
        */

        $count = $lobby
            ->players()
            ->count();

        /*
        |--------------------------------------------------------------------------
        | Приглашение
        |--------------------------------------------------------------------------
        */

        $inviteLink =
            "https://t.me/YkSUS10_bot?start=lobby_{$lobby->id}";

        /*
        |--------------------------------------------------------------------------
        | Имя создателя
        |--------------------------------------------------------------------------
        |
        | Используем username, если он есть.
        | Иначе first_name.
        |
        */

        $creatorName = 'Игрок';

        if ($user->username) {

            $creatorName =
                '@' . $user->username;

        } elseif ($user->first_name) {

            $creatorName =
                $user->first_name;
        }

        $inviteText =
            "🎮 Приглашение в лобби\n\n" .
            "👑 Создал: {$creatorName}\n" .
            "👥 Игроки: {$count}/{$lobby->max_players}\n" .
            "🔗 Войти в лобби:\n" .
            $inviteLink;

        /*
        |--------------------------------------------------------------------------
        | Queue
        |--------------------------------------------------------------------------
        */

        SendLobbyNotificationsJob::dispatch(
            $lobby->id,
            $telegramId,
            $creatorName,
            $count
        );

        /*
        |--------------------------------------------------------------------------
        | Сообщение создателю
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                "🎮 Лобби создано!\n\n" .
                "🆔 Лобби #{$lobby->id}\n" .
                "🔑 Код игры: {$lobby->game_room_code}\n\n" .
                "👥 Игроки: {$count}/{$lobby->max_players}\n\n" .
                "Ожидаем игроков.",

            'reply_markup' => json_encode([
                'inline_keyboard' => [
                    [
                        [
                            'text' => '📋 Скопировать приглашение',

                            'copy_text' => [
                                'text' => $inviteText
                            ]
                        ]
                    ]
                ]
            ])
        ]);

        /*
        |--------------------------------------------------------------------------
        | Обычная клавиатура
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                '🎮 Управление лобби:',

            'reply_markup' => json_encode([
                'keyboard' => [
                    [
                        [
                            'text' => '🎮 Моё лобби'
                        ]
                    ],

                    [
                        [
                            'text' => '⬅️ Главное меню'
                        ]
                    ]
                ],

                'resize_keyboard' => true
            ])
        ]);

        return true;
    }
}