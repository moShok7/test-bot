<?php

namespace App\Services\Bot\Lobby;

use App\Jobs\SendLobbyNotificationsJob;
use App\Models\BotSession;
use App\Models\TelegramUser;
use App\Models\Lobby;
use App\Models\LobbyPlayer;
use Carbon\Carbon;

class CreateLobbyHandler
{
    /**
     * Время жизни сессии создания лобби.
     */
    private const SESSION_TIMEOUT_MINUTES = 5;

    public function handle($message, $telegram): bool
    {
        $text = trim($message->text ?? '');

        $telegramId = $message->from->id ?? null;

        if (!$telegramId) {
            return false;
        }

        $chatId = $message->chat->id ?? $telegramId;

        /*
        |--------------------------------------------------------------------------
        | Получаем TelegramUser
        |--------------------------------------------------------------------------
        */

        $user = TelegramUser::where(
            'telegram_id',
            $telegramId
        )->first();

        if (!$user) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Получаем текущую сессию
        |--------------------------------------------------------------------------
        */

        $session = BotSession::where(
            'telegram_user_id',
            $user->id
        )->first();

        /*
        |--------------------------------------------------------------------------
        | Проверяем таймаут сессии
        |--------------------------------------------------------------------------
        |
        | Если пользователь начал создание лобби и прошло больше 5 минут,
        | старая сессия удаляется.
        |
        */

        if ($session) {

            $sessionCreatedAt = $session->created_at;

            if (
                $sessionCreatedAt &&
                Carbon::parse($sessionCreatedAt)
                    ->addMinutes(self::SESSION_TIMEOUT_MINUTES)
                    ->isPast()
            ) {
                $session->delete();

                $session = null;
            }
        }

        /*
        |--------------------------------------------------------------------------
        | Главное меню
        |--------------------------------------------------------------------------
        |
        | ВАЖНО:
        | Проверяем кнопку ДО обработки старой сессии.
        |
        | Поэтому если пользователь нажал "Главное меню",
        | сессия гарантированно удаляется.
        |
        */

        if ($text === '⬅️ Главное меню') {

            BotSession::where(
                'telegram_user_id',
                $user->id
            )->delete();

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' => '🎮 Игровое меню',

                'reply_markup' => json_encode([
                    'keyboard' => [
                        [
                            [
                                'text' => '➕ Создать лобби'
                            ],
                            [
                                'text' => '🔍 Найти лобби'
                            ]
                        ],
                        [
                            [
                                'text' => '🎮 Моё лобби'
                            ]
                        ],
                        [
                            [
                                'text' => '⚙️ Настройки'
                            ]
                        ]
                    ],

                    'resize_keyboard' => true
                ])
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Другие кнопки меню
        |--------------------------------------------------------------------------
        |
        | Если пользователь нажал другую функцию, старая сессия создания
        | лобби больше не должна перехватывать следующие сообщения.
        |
        */

        if (
            $text === '🔍 Найти лобби' ||
            $text === '🔄 Обновить поиск' ||
            $text === '🎮 Моё лобби' ||
            $text === '⚙️ Настройки'
        ) {

            BotSession::where(
                'telegram_user_id',
                $user->id
            )->delete();

            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Кнопка "Создать лобби"
        |--------------------------------------------------------------------------
        */

        if ($text === '➕ Создать лобби') {

            /*
            |--------------------------------------------------------------------------
            | Проверяем активное лобби
            |--------------------------------------------------------------------------
            */

            $already = LobbyPlayer::where(
                'telegram_user_id',
                $user->id
            )
            ->whereHas(
                'lobby',
                function ($query) {
                    $query->whereIn(
                        'status',
                        [
                            'waiting',
                            'playing'
                        ]
                    );
                }
            )
            ->exists();

            /*
            |--------------------------------------------------------------------------
            | Пользователь уже находится в лобби
            |--------------------------------------------------------------------------
            */

            if ($already) {

                $lobby = Lobby::whereIn(
                    'status',
                    [
                        'waiting',
                        'playing'
                    ]
                )
                ->whereHas(
                    'players',
                    function ($query) use ($user) {
                        $query->where(
                            'telegram_user_id',
                            $user->id
                        );
                    }
                )
                ->first();

                $isHost =
                    $lobby &&
                    $lobby->creator_id == $user->id;

                if ($isHost) {

                    $keyboard = [

                        [
                            [
                                'text' => '👥 Игроки'
                            ]
                        ],

                        [
                            [
                                'text' => '❌ Кикнуть игрока'
                            ]
                        ],

                        [
                            [
                                'text' => '📤 Приглашение'
                            ]
                        ],

                        [
                            [
                                'text' => '▶️ Начать игру'
                            ]
                        ],

                        [
                            [
                                'text' => '✏️ Изменить код'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];

                } else {

                    $keyboard = [

                        [
                            [
                                'text' => '🎮 Моё лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];
                }

                $telegram->sendMessage([
                    'chat_id' => $chatId,

                    'text' =>
                        "⚠️ Вы уже состоите в активном лобби.\n\n" .
                        "Откройте: 🎮 Моё лобби",

                    'reply_markup' => json_encode([
                        'keyboard' => $keyboard,
                        'resize_keyboard' => true
                    ])
                ]);

                return true;
            }

            /*
            |--------------------------------------------------------------------------
            | Удаляем старую сессию перед созданием новой
            |--------------------------------------------------------------------------
            */

            BotSession::where(
                'telegram_user_id',
                $user->id
            )->delete();

            /*
            |--------------------------------------------------------------------------
            | Создаём новую сессию
            |--------------------------------------------------------------------------
            */

            BotSession::create([
                'telegram_user_id' => $user->id,
                'step' => 'lobby_code'
            ]);

            /*
            |--------------------------------------------------------------------------
            | Просим код
            |--------------------------------------------------------------------------
            */

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "🎮 Создайте комнату в игре.\n\n" .
                    "После этого отправьте код комнаты.\n\n" .
                    "⏱ У вас есть 5 минут.\n\n" .
                    "Или нажмите кнопку ниже, чтобы вернуться.",

                'reply_markup' => json_encode([
                    'keyboard' => [
                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ],

                    'resize_keyboard' => true
                ])
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Если нет активной сессии
        |--------------------------------------------------------------------------
        |
        | Обычные сообщения пользователя здесь не обрабатываем.
        |
        */

        if (!$session) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Сессия должна быть именно lobby_code
        |--------------------------------------------------------------------------
        */

        if ($session->step !== 'lobby_code') {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | СТРОГАЯ ПРОВЕРКА КОДА
        |--------------------------------------------------------------------------
        |
        | Ровно 6 символов.
        |
        | Разрешены:
        | A-Z
        | a-z
        | 0-9
        |
        | Всё остальное просто игнорируем.
        |
        */

        if (!preg_match('/^[A-Za-z0-9]{6}$/', $text)) {

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Создаём лобби
        |--------------------------------------------------------------------------
        */

        $lobby = Lobby::create([
            'creator_id' => $user->id,

            'game_room_code' => $text,

            'status' => 'waiting',

            'min_players' => 4,

            'max_players' => 12,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Добавляем создателя
        |--------------------------------------------------------------------------
        */

        LobbyPlayer::create([
            'lobby_id' => $lobby->id,

            'telegram_user_id' => $user->id,

            'ready' => false,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Удаляем сессию
        |--------------------------------------------------------------------------
        */

        $session->delete();

        /*
        |--------------------------------------------------------------------------
        | Количество игроков
        |--------------------------------------------------------------------------
        */

        $count = $lobby
            ->players()
            ->count();

        /*
        |--------------------------------------------------------------------------
        | Имя создателя
        |--------------------------------------------------------------------------
        */

        $creatorName = 'Игрок';

        if (!empty($user->first_name)) {

            $creatorName = $user->first_name;

        } elseif (!empty($user->username)) {

            $creatorName =
                '@' . $user->username;
        }

        /*
        |--------------------------------------------------------------------------
        | Ссылка приглашения
        |--------------------------------------------------------------------------
        */

        $inviteLink =
            "https://t.me/YkSUS10_bot?start=lobby_{$lobby->id}";

        $inviteText =
            "🎮 Приглашение в лобби\n\n" .
            "👑 Создал: {$creatorName}\n" .
            "👥 Игроки: {$count}/{$lobby->max_players}\n" .
            "🔗 Войти в лобби:\n" .
            $inviteLink;

        /*
        |--------------------------------------------------------------------------
        | Queue уведомлений
        |--------------------------------------------------------------------------
        */

        SendLobbyNotificationsJob::dispatch(
            $lobby->id,
            $telegramId,
            $creatorName,
            $count
        );

        /*
        |--------------------------------------------------------------------------
        | Сообщение создателю
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                "🎮 Лобби создано!\n\n" .
                "🆔 Лобби #{$lobby->id}\n" .
                "🔑 Код игры: {$lobby->game_room_code}\n\n" .
                "👥 Игроки: {$count}/{$lobby->max_players}\n\n" .
                "Ожидаем игроков.",

            'reply_markup' => json_encode([
                'inline_keyboard' => [
                    [
                        [
                            'text' => '📋 Скопировать приглашение',

                            'copy_text' => [
                                'text' => $inviteText
                            ]
                        ]
                    ]
                ]
            ])
        ]);

        /*
        |--------------------------------------------------------------------------
        | Клавиатура управления
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                '🎮 Управление лобби:',

            'reply_markup' => json_encode([
                'keyboard' => [
                    [
                        [
                            'text' => '🎮 Моё лобби'
                        ]
                    ],

                    [
                        [
                            'text' => '⬅️ Главное меню'
                        ]
                    ]
                ],

                'resize_keyboard' => true
            ])
        ]);

        return true;
    }
}
