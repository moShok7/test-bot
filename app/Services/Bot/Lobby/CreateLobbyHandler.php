<?php

namespace App\Services\Bot\Lobby;

use App\Jobs\SendLobbyNotificationsJob;
use App\Models\BotSession;
use App\Models\TelegramUser;
use App\Models\Lobby;
use App\Models\LobbyPlayer;
use Carbon\Carbon;

class CreateLobbyHandler
{
    /**
     * Сессия создания лобби живёт 5 минут.
     */
    private const SESSION_TIMEOUT_MINUTES = 5;

    public function handle($message, $telegram): bool
    {
        $text = trim($message->text ?? '');

        $telegramId = $message->from->id ?? null;

        if (!$telegramId) {
            return false;
        }

        $chatId = $message->chat->id ?? $telegramId;

        /*
        |--------------------------------------------------------------------------
        | Получаем TelegramUser
        |--------------------------------------------------------------------------
        |
        | ВАЖНО:
        | BotSession.telegram_user_id хранит telegram_users.id,
        | а НЕ настоящий Telegram ID.
        |
        */

        $user = TelegramUser::where(
            'telegram_id',
            $telegramId
        )->first();

        if (!$user) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Очищаем просроченную сессию
        |--------------------------------------------------------------------------
        */

        $session = BotSession::where(
            'telegram_user_id',
            $user->id
        )->first();

        if ($session) {

            $createdAt = $session->created_at;

            if (
                $createdAt &&
                Carbon::parse($createdAt)
                    ->addMinutes(self::SESSION_TIMEOUT_MINUTES)
                    ->isPast()
            ) {
                $session->delete();

                $session = null;
            }
        }

        /*
        |--------------------------------------------------------------------------
        | Главное меню
        |--------------------------------------------------------------------------
        */

        if ($text === '⬅️ Главное меню') {

            /*
            | ВАЖНО:
            | Используем $user->id, потому что именно его
            | хранит bot_sessions.telegram_user_id.
            */

            BotSession::where(
                'telegram_user_id',
                $user->id
            )->delete();

            $this->sendMainMenu(
                $chatId,
                $telegram
            );

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Другие кнопки меню
        |--------------------------------------------------------------------------
        |
        | Если пользователь находится в старой сессии создания,
        | эти кнопки должны сбрасывать её.
        |
        */

        if (
            $text === '🔍 Найти лобби' ||
            $text === '🔄 Обновить поиск' ||
            $text === '🎮 Моё лобби' ||
            $text === '⚙️ Настройки'
        ) {

            BotSession::where(
                'telegram_user_id',
                $user->id
            )->delete();

            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Нажата кнопка "➕ Создать лобби"
        |--------------------------------------------------------------------------
        */

        if ($text === '➕ Создать лобби') {

            /*
            |--------------------------------------------------------------------------
            | Проверяем активное лобби
            |--------------------------------------------------------------------------
            */

            $already = LobbyPlayer::where(
                'telegram_user_id',
                $user->id
            )
            ->whereHas(
                'lobby',
                function ($query) {
                    $query->whereIn(
                        'status',
                        [
                            'waiting',
                            'playing'
                        ]
                    );
                }
            )
            ->exists();

            /*
            |--------------------------------------------------------------------------
            | Если пользователь уже в лобби
            |--------------------------------------------------------------------------
            */

            if ($already) {

                $lobby = Lobby::whereIn(
                    'status',
                    [
                        'waiting',
                        'playing'
                    ]
                )
                ->whereHas(
                    'players',
                    function ($q) use ($user) {
                        $q->where(
                            'telegram_user_id',
                            $user->id
                        );
                    }
                )
                ->first();

                $isHost =
                    $lobby &&
                    $lobby->creator_id == $user->id;

                if ($isHost) {

                    $keyboard = [

                        [
                            [
                                'text' => '👥 Игроки'
                            ]
                        ],

                        [
                            [
                                'text' => '❌ Кикнуть игрока'
                            ]
                        ],

                        [
                            [
                                'text' => '📤 Приглашение'
                            ]
                        ],

                        [
                            [
                                'text' => '▶️ Начать игру'
                            ]
                        ],

                        [
                            [
                                'text' => '✏️ Изменить код'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];

                } else {

                    $keyboard = [

                        [
                            [
                                'text' => '🎮 Моё лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '🚪 Выйти из лобби'
                            ]
                        ],

                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ];
                }

                $telegram->sendMessage([
                    'chat_id' => $chatId,

                    'text' =>
                        "⚠️ Вы уже состоите в активном лобби.\n\n" .
                        "Откройте: 🎮 Моё лобби",

                    'reply_markup' => json_encode([
                        'keyboard' => $keyboard,
                        'resize_keyboard' => true
                    ])
                ]);

                return true;
            }

            /*
            |--------------------------------------------------------------------------
            | Создаём/обновляем сессию ожидания кода
            |--------------------------------------------------------------------------
            */

            BotSession::updateOrCreate(
                [
                    'telegram_user_id' => $user->id
                ],
                [
                    'step' => 'lobby_code'
                ]
            );

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "🎮 Создайте комнату в игре.\n\n" .
                    "После этого отправьте код комнаты.\n\n" .
                    "⏱ У вас есть 5 минут.\n\n" .
                    "Или нажмите кнопку ниже, чтобы вернуться.",

                'reply_markup' => json_encode([
                    'keyboard' => [
                        [
                            [
                                'text' => '⬅️ Главное меню'
                            ]
                        ]
                    ],

                    'resize_keyboard' => true
                ])
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Получаем актуальную сессию
        |--------------------------------------------------------------------------
        */

        $session = BotSession::where(
            'telegram_user_id',
            $user->id
        )->first();

        /*
        |--------------------------------------------------------------------------
        | Нет активной сессии
        |--------------------------------------------------------------------------
        |
        | Очень важно:
        | Обычный текст вроде "Привет всем" больше не считается кодом.
        |
        */

        if (!$session) {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Проверяем шаг
        |--------------------------------------------------------------------------
        */

        if ($session->step !== 'lobby_code') {
            return false;
        }

        /*
        |--------------------------------------------------------------------------
        | Дополнительная проверка таймаута
        |--------------------------------------------------------------------------
        */

        if (
            $session->created_at &&
            Carbon::parse($session->created_at)
                ->addMinutes(self::SESSION_TIMEOUT_MINUTES)
                ->isPast()
        ) {

            $session->delete();

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "⏱ Время ожидания кода истекло.\n\n" .
                    "Создайте лобби заново."
            ]);

            $this->sendMainMenu(
                $chatId,
                $telegram
            );

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Проверяем код
        |--------------------------------------------------------------------------
        */

        if (!$text) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Отправьте код комнаты."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Максимальная длина
        |--------------------------------------------------------------------------
        */

        if (strlen($text) > 50) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Код комнаты слишком длинный.\n" .
                    "Отправьте только код из игры."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Разрешённые символы
        |--------------------------------------------------------------------------
        */

        if (!preg_match('/^[a-zA-Z0-9_-]+$/', $text)) {

            $telegram->sendMessage([
                'chat_id' => $chatId,

                'text' =>
                    "❌ Неверный код комнаты.\n\n" .
                    "Используйте только буквы, цифры, _ и -."
            ]);

            return true;
        }

        /*
        |--------------------------------------------------------------------------
        | Создаём лобби
        |--------------------------------------------------------------------------
        */

        $lobby = Lobby::create([
            'creator_id' =>
                $user->id,

            'game_room_code' =>
                $text,

            'status' =>
                'waiting',

            'min_players' =>
                4,

            'max_players' =>
                12,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Добавляем создателя
        |--------------------------------------------------------------------------
        */

        LobbyPlayer::create([
            'lobby_id' =>
                $lobby->id,

            'telegram_user_id' =>
                $user->id,

            'ready' =>
                false,
        ]);

        /*
        |--------------------------------------------------------------------------
        | Удаляем сессию
        |--------------------------------------------------------------------------
        */

        $session->delete();

        /*
        |--------------------------------------------------------------------------
        | Количество игроков
        |--------------------------------------------------------------------------
        */

        $count = $lobby
            ->players()
            ->count();

        /*
        |--------------------------------------------------------------------------
        | Приглашение
        |--------------------------------------------------------------------------
        */

        $inviteLink =
            "https://t.me/YkSUS10_bot?start=lobby_{$lobby->id}";

        /*
        |--------------------------------------------------------------------------
        | Имя создателя
        |--------------------------------------------------------------------------
        */

        $creatorName = 'Игрок';

        if ($user->first_name) {

            $creatorName =
                $user->first_name;

        } elseif ($user->username) {

            $creatorName =
                '@' . $user->username;
        }

        $inviteText =
            "🎮 Приглашение в лобби\n\n" .
            "👑 Создал: {$creatorName}\n" .
            "👥 Игроки: {$count}/{$lobby->max_players}\n" .
            "🔗 Войти в лобби:\n" .
            $inviteLink;

        /*
        |--------------------------------------------------------------------------
        | Queue уведомлений
        |--------------------------------------------------------------------------
        */

        SendLobbyNotificationsJob::dispatch(
            $lobby->id,
            $telegramId,
            $creatorName,
            $count
        );

        /*
        |--------------------------------------------------------------------------
        | Сообщение создателю
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                "🎮 Лобби создано!\n\n" .
                "🆔 Лобби #{$lobby->id}\n" .
                "🔑 Код игры: {$lobby->game_room_code}\n\n" .
                "👥 Игроки: {$count}/{$lobby->max_players}\n\n" .
                "Ожидаем игроков.",

            'reply_markup' => json_encode([
                'inline_keyboard' => [
                    [
                        [
                            'text' =>
                                '📋 Скопировать приглашение',

                            'copy_text' => [
                                'text' =>
                                    $inviteText
                            ]
                        ]
                    ]
                ]
            ])
        ]);

        /*
        |--------------------------------------------------------------------------
        | Обычная клавиатура
        |--------------------------------------------------------------------------
        */

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                '🎮 Управление лобби:',

            'reply_markup' => json_encode([
                'keyboard' => [
                    [
                        [
                            'text' =>
                                '🎮 Моё лобби'
                        ]
                    ],

                    [
                        [
                            'text' =>
                                '⬅️ Главное меню'
                        ]
                    ]
                ],

                'resize_keyboard' => true
            ])
        ]);

        return true;
    }


    /*
    |--------------------------------------------------------------------------
    | Главное меню
    |--------------------------------------------------------------------------
    */

    private function sendMainMenu(
        $chatId,
        $telegram
    ) {

        $telegram->sendMessage([
            'chat_id' => $chatId,

            'text' =>
                '🏠 Главное меню',

            'reply_markup' => json_encode([
                'keyboard' => [
                    [
                        [
                            'text' =>
                                '➕ Создать лобби'
                        ],
                        [
                            'text' =>
                                '🔍 Найти лобби'
                        ]
                    ],

                    [
                        [
                            'text' =>
                                '🎮 Моё лобби'
                        ]
                    ],

                    [
                        [
                            'text' =>
                                '⚙️ Настройки'
                        ]
                    ]
                ],

                'resize_keyboard' => true
            ])
        ]);
    }
}

